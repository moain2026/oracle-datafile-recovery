#!/usr/bin/env python3
"""Generate crates/odr-core/src/charset/tables.rs from authoritative mapping files.

Every single-byte table is cross-checked against an independent second source
before it is written; any disagreement aborts generation (ADR-0005: no silent
guesses). Sources live in tools/charset-sources/ (Unicode licence / WHATWG BSD).

    python3 tools/gen_charsets.py          # regenerate
    python3 tools/gen_charsets.py --check  # CI: fail if tables.rs is stale
"""
import codecs, hashlib, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "tools" / "charset-sources"
OUT = ROOT / "crates" / "odr-core" / "src" / "charset" / "tables.rs"


def unicode_org(name):
    """Parse a Unicode-consortium mapping file: high half only, missing = 0."""
    m = [0] * 128
    for line in (SRC / name).read_text(encoding="latin-1").splitlines():
        f = line.split("#")[0].split()
        if len(f) >= 2 and f[0].startswith("0x"):
            b, u = int(f[0], 16), int(f[1], 16)
            if b >= 0x80:
                m[b - 0x80] = u
    return m


def whatwg(name):
    m = [0] * 128
    for line in (SRC / name).read_text(encoding="utf-8").splitlines():
        if line.startswith("#") or not line.strip():
            continue
        f = line.split()
        m[int(f[0])] = int(f[1], 16)
    return m


def python_codec(codec):
    m = [0] * 128
    for b in range(0x80, 0x100):
        try:
            m[b - 0x80] = ord(bytes([b]).decode(codec))
        except UnicodeDecodeError:
            pass
    return m


def agree(name, a, b, ignore=()):
    bad = [hex(0x80 + i) for i in range(128) if a[i] != b[i] and 0x80 + i not in ignore]
    if bad:
        sys.exit(f"{name}: sources disagree at {bad}")


cp1256 = unicode_org("CP1256.TXT")
agree("CP1256 unicode.org vs WHATWG", cp1256, whatwg("index-windows-1256.txt"))
agree("CP1256 unicode.org vs Python", cp1256, python_codec("cp1256"))
assert all(cp1256), "CP1256 must define all 128 high bytes"

cp1252 = unicode_org("CP1252.TXT")  # 0x81 0x8D 0x8F 0x90 0x9D undefined (Microsoft)
agree("CP1252 unicode.org vs WHATWG", cp1252, whatwg("index-windows-1252.txt"),
      ignore={0x81, 0x8D, 0x8F, 0x90, 0x9D})  # WHATWG maps them to C1 controls
agree("CP1252 unicode.org vs Python", cp1252, python_codec("cp1252"))

iso6 = unicode_org("8859-6.TXT")
agree("8859-6 unicode.org vs Python", iso6, python_codec("iso8859_6"))

latin1 = [0x80 + i for i in range(128)]  # identity by definition


def emit(name, doc, table):
    rows = []
    for i in range(0, 128, 8):
        rows.append("    " + " ".join(f"0x{u:04X}," for u in table[i:i + 8]))
    return f"/// {doc}\n/// Index = byte − 0x80; `0` = byte not defined in this character set.\npub(super) static {name}: [u16; 128] = [\n" + "\n".join(rows) + "\n];\n"


src_hash = hashlib.sha256(b"".join((SRC / n).read_bytes() for n in sorted(p.name for p in SRC.iterdir()))).hexdigest()
body = (
    "//! GENERATED by `tools/gen_charsets.py` — do not edit by hand.\n"
    f"//! Source files SHA-256 (sorted, concatenated): {src_hash}\n"
    "//! Each table was cross-checked against an independent second source.\n\n"
    + emit("CP1256", "Windows-1256 (Oracle `AR8MSWIN1256`). unicode.org = WHATWG = Python.", cp1256) + "\n"
    + emit("CP1252", "Windows-1252 (Oracle `WE8MSWIN1252`). unicode.org = Python; 5 bytes undefined.", cp1252) + "\n"
    + emit("ISO8859_6", "ISO-8859-6 (Oracle `AR8ISO8859P6`). unicode.org = Python.", iso6) + "\n"
    + emit("ISO8859_1", "ISO-8859-1 (Oracle `WE8ISO8859P1`): identity.", latin1)
)
if "--check" in sys.argv:
    sys.exit(0 if OUT.read_text() == body else "tables.rs is stale: run tools/gen_charsets.py")
OUT.write_text(body)
print(f"wrote {OUT.relative_to(ROOT)}")
