-- Tablespaces for the golden corpus. All SMALLFILE on purpose: 23ai/26ai default to
-- BIGFILE (LV-031), and both rdba schemes must be covered explicitly.
-- One tablespace per storage variant so every datafile has a known purpose.
WHENEVER SQLERROR EXIT FAILURE
SET ECHO ON
ALTER SESSION SET CONTAINER = &1;
CREATE SMALLFILE TABLESPACE ODR_ASSM DATAFILE '/opt/oracle/oradata/odr/odr_assm01.dbf' SIZE 64M
  EXTENT MANAGEMENT LOCAL UNIFORM SIZE 1M SEGMENT SPACE MANAGEMENT AUTO;
CREATE SMALLFILE TABLESPACE ODR_MSSM DATAFILE '/opt/oracle/oradata/odr/odr_mssm01.dbf' SIZE 64M
  EXTENT MANAGEMENT LOCAL UNIFORM SIZE 1M SEGMENT SPACE MANAGEMENT MANUAL;
CREATE BIGFILE TABLESPACE ODR_BIG DATAFILE '/opt/oracle/oradata/odr/odr_big01.dbf' SIZE 64M
  EXTENT MANAGEMENT LOCAL UNIFORM SIZE 1M SEGMENT SPACE MANAGEMENT AUTO;
CREATE USER ODR IDENTIFIED BY "&2" DEFAULT TABLESPACE ODR_ASSM QUOTA UNLIMITED ON ODR_ASSM
  QUOTA UNLIMITED ON ODR_MSSM QUOTA UNLIMITED ON ODR_BIG;
GRANT CREATE SESSION, CREATE TABLE, CREATE CLUSTER, CREATE VIEW TO ODR;
EXIT
